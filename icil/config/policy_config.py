from dataclasses import dataclass
@dataclass
class PolicyConfig:
    n_encoder_layers: int = 4
    dim_model: int = 16
    dim_feedforward: int = 64
    n_heads: int = 4
    dropout: int = 0.1
    pre_norm: bool = False
